    $staff = htmlspecialchars($to['staff_name'] ?: 'Visal');
    $pm_raw = strtolower(trim((string)($to['payment_method'] ?? 'cash')));
    if ($pm_raw === 'bakong' || $pm_raw === 'khqr') {
        $pm_text = 'Bakong';
