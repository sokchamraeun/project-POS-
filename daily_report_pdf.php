    $orderNoStr   = '#' . str_pad((string)$dailyOrderNo, 4, '0', STR_PAD_LEFT);
    $oid   = (int)$to['order_id'];
    $disc  = (float)($to['discount_amount'] ?? 0);
    $net   = (float)$to['total'];
    $gross = $net + $disc;
    $ocogs = (float)($cogsByOrder[$oid] ?? 0.0);
    $profit = $net - $ocogs;

    $o_its = $items_by_order[$oid] ?? [];
    $o_qty = 0;
    foreach ($o_its as $oit) {
        $o_qty += max(1, (int)($oit['quantity'] ?? 1));
    }

    $sum_gross  += $gross;
    $sum_disc   += $disc;
    $sum_net    += $net;
    $sum_cogs   += $ocogs;
    $sum_profit += $profit;
    $sum_qty    += $o_qty;

    $date_str = date('g:i j/n/Y', strtotime($to['order_date']));
    $raw_cust = trim($to['customer_name'] ?? '');
    if ($raw_cust === '' || strtolower($raw_cust) === 'general' || strtolower($raw_cust) === 'guest') {
        $cust = 'General';
