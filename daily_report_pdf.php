        'no'         => $orderNoStr,
        'date'       => $date_str,
        'customer'   => $cust,
        'price'      => fmtNum($gross),
        'qty_item'   => $o_qty,
        'total'      => fmtNum($net),
        'cogs'       => fmtNum($ocogs),
        'profit'     => fmtNum($profit),
        'currency'   => '$',
        'place_by'   => $staff,
    ];
}

