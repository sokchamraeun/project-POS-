        'no'             => $orderNoStr,
        'date'           => $date_str,
        'customer'       => $cust,
        'price'          => fmtNum($gross),
        'qty_item'       => $o_qty,
        'payment_method' => $pm_text,
        'total'          => fmtNum($net),
        'cogs'           => fmtNum($ocogs),
        'profit'         => fmtNum($profit),
        'profit_val'     => $profit,
        'currency'       => '$',
        'place_by'       => $staff,
    ];
}

