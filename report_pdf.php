        'price_cup'   => fmtMoney($unitPrice),
        'discount'    => fmtDisc((float)($p['discount'] ?? 0)),
        'revenue'     => fmtMoney($rev),
        'cogs'        => fmtMoney($cogs),
        'profit'      => fmtMoney($profit),
        'margin'      => $margin . '%',
    ];
}

