// ── Paid orders in range ──
$where_conds = ["DATE(o.order_date) BETWEEN '$dateFrom' AND '$dateTo'", paid_orders_where()];
$filter_payment = trim($_GET['payment_method'] ?? '');
if ($filter_payment !== '') { $where_conds[] = "LOWER(o.payment_method) = '" . $conn->real_escape_string(strtolower($filter_payment)) . "'"; }
$where_str = implode(' AND ', $where_conds);

$qOrders = $conn->query("SELECT o.order_id FROM orders o WHERE $where_str");
$orderIds = [];
if ($qOrders) {
    while ($o = $qOrders->fetch_assoc()) {
        $orderIds[] = (int)$o['order_id'];
    }
}

$topProducts = [];
$totalItemsSold = 0;
$totalSalesRevenue = 0.0;
$totalCOGSAmount = 0.0;
$totalDiscountAmount = 0.0;

$filter_cat = trim($_GET['category'] ?? '');
if (!empty($orderIds)) {
    $inOrder = implode(',', $orderIds);
    $cat_where = '';
    if ($filter_cat !== '') {
        $esc_cat = $conn->real_escape_string($filter_cat);
        $cat_where = " AND (p.category = '$esc_cat' OR oi.category = '$esc_cat')";
    }
    $qItems = $conn->query("
        SELECT oi.product_id, oi.product_name, oi.milk, oi.quantity, oi.price,
               COALESCE(oi.orig_price, oi.price) AS orig_price,
               COALESCE(oi.promo_percent, 0) AS promo_percent,
               COALESCE(NULLIF(p.category,''),'Uncategorized') AS category
        FROM order_items oi
        LEFT JOIN products p ON p.product_id = oi.product_id
        WHERE oi.order_id IN ($inOrder) $cat_where
    ");
    $items = [];
    $productIds = [];
    if ($qItems) {
        while ($it = $qItems->fetch_assoc()) {
            $items[] = $it;
            if ((int)$it['product_id'] > 0) { $productIds[(int)$it['product_id']] = true; }
        }
    }

    $recipes = [];

    foreach ($items as $it) {
        $pid      = (int)$it['product_id'];
        $qty      = max(1, (int)$it['quantity']);
        $milkType = trim((string)$it['milk']);
        $pname    = trim((string)$it['product_name']);
        $category = trim((string)$it['category']) ?: 'Uncategorized';
        $itemCost = 0.0;

        if (isset($recipes[$pid])) {
            foreach ($recipes[$pid] as $rc) {
                $amount = (float)$rc['amount_used'] * $qty;
                if ($amount <= 0) continue;
                if (strpos(strtolower(trim($rc['ingredient_name'])), 'milk') !== false) {
                    $key = strtolower(trim($milkType !== '' ? $milkType : 'Fresh Milk'));
                    if (isset($cost_map_ref[$key])) {
                        $itemCost += $amount * (float)$cost_map_ref[$key]['unit_cost'];
                    }
                } else {
                    $iid = (int)$rc['ingredient_id'];
                    $itemCost += $amount * (float)($cost_map_ref[$iid]['unit_cost'] ?? 0);
                }
            }
        }

        $origPrice = (float)($it['orig_price'] > 0 ? $it['orig_price'] : $it['price']);
        $sellingPrice = (float)($it['price'] ?? 0);
        $promoPct = (float)($it['promo_percent'] ?? 0);
        $itemDiscUnit = 0;
        if ($origPrice > $sellingPrice) {
            $itemDiscUnit = $origPrice - $sellingPrice;
        } elseif ($promoPct > 0) {
            $itemDiscUnit = $sellingPrice * ($promoPct / 100);
        }
        $itemTotalDisc = $itemDiscUnit * $qty;

        $revenue = (float)$it['price'] * $qty;
        $totalItemsSold += $qty;
        $totalSalesRevenue += $revenue;
        $totalCOGSAmount += $itemCost;
        $totalDiscountAmount += $itemTotalDisc;

        if (!isset($topProducts[$pname])) {
            $topProducts[$pname] = [
                'qty'      => 0,
                'cogs'     => 0.0,
                'revenue'  => 0.0,
                'discount' => 0.0,
                'category' => $category
            ];
        }
        $topProducts[$pname]['qty']      += $qty;
        $topProducts[$pname]['cogs']     += $itemCost;
        $topProducts[$pname]['revenue']  += $revenue;
        $topProducts[$pname]['discount'] += $itemTotalDisc;
    }

    uasort($topProducts, fn($a, $b) => $b['revenue'] <=> $a['revenue']);
}

$totalGrossProfit = $totalSalesRevenue - $totalCOGSAmount;

function fmtMoney($amt) {
    return ($amt == floor($amt) ? number_format($amt, 0) : number_format($amt, 2)) . '$';
}
function fmtDisc($amt) {
    if ($amt == 0) return '0';
    return fmtMoney($amt);
}

