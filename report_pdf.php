    $idx++;
    $qty     = (int)$p['qty'];
    $rev     = (float)$p['revenue'];
    $cogs    = (float)$p['cogs'];
    $profit  = $rev - $cogs;
    $margin  = $rev > 0 ? round(($profit / $rev) * 100) : 0;
    $unitPrice = $qty > 0 ? ($rev / $qty) : 0;

